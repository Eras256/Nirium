// ─── Utility Functions ───────────────────────────────────────────

/**
 * Generate a UUID v4 for use as customerId or bankAccountId.
 * The Etherfuse API requires proper UUIDs.
 */
export function generateUUID(): string {
    return crypto.randomUUID();
}

/**
 * Get or create persistent customer/bank IDs for a wallet address.
 * Stores in localStorage so the same wallet always maps to the same customer.
 */
export function getOrCreateCustomerIds(walletAddress: string): {
    customerId: string;
    bankAccountId: string;
} {
    const storageKey = `nirium-etherfuse-customer-${walletAddress}`;
    
    if (typeof window !== 'undefined') {
        const stored = localStorage.getItem(storageKey);
        if (stored) {
            try {
                return JSON.parse(stored);
            } catch { /* regenerate */ }
        }
    }

    const ids = {
        customerId: crypto.randomUUID(),
        bankAccountId: crypto.randomUUID(),
    };

    if (typeof window !== 'undefined') {
        localStorage.setItem(storageKey, JSON.stringify(ids));
    }

    return ids;
}
